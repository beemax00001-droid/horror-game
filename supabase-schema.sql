-- Optional helper view for reports (visible only to members through RLS-backed base queries).
create or replace view public.khatm_report as
select k.id,k.name,k.code,k.status,k.created_at,k.completed_at,
       count(distinct p.id)::int as participant_count,
       count(distinct case when j.status='completed' then j.id end)::int as completed_juz
from public.khatms k
left join public.participants p on p.khatm_id=k.id
left join public.juz_assignments j on j.khatm_id=k.id
group by k.id,k.name,k.code,k.status,k.created_at,k.completed_at;

